def test_screenshots_are_taken_of_the_input_and_the_output(tmp_path, monkeypatch):
    taken = []
    monkeypatch.setattr(extras, "capture", lambda shots: taken.extend(shots))
    original = tmp_path / "in" / "page.html"
    original.parent.mkdir()
    original.write_text("<p>a</p>", encoding="utf-8")
    target = tmp_path / "out" / "page.html"
    target.parent.mkdir()
    target.write_text("<p>b</p>", encoding="utf-8")
    entries = extras.page_extras("html", "page.html", original, "<p>a</p>", "<p>b</p>", target,
                                 react=False, screenshot=True, component="LandingPage")
    assert [(url.rsplit("/", 1)[-1], png.name) for url, png in taken] == [
        ("page.html", "page.before.png"), ("page.html", "page.after.png")]
    assert taken[0][0].endswith("/in/page.html") and taken[1][0].endswith("/out/page.html")
    assert entries == [Entry("page.html", "screenshot", "note", reason="wrote page.before.png and page.after.png")]


def test_a_markdown_page_gets_a_temporary_before_file_that_finds_its_images(tmp_path, monkeypatch):
    seen = {}

    def fake(shots):
        seen["before"] = shots[0][0]
        seen["text"] = __import__("pathlib").Path(__import__("urllib.request").request.url2pathname(
            shots[0][0].removeprefix("file:///"))).read_text(encoding="utf-8")

    monkeypatch.setattr(extras, "capture", fake)
    original = tmp_path / "notes.md"
    original.write_text("# N\n", encoding="utf-8")
    target = tmp_path / "out" / "notes.html"
    target.parent.mkdir()
    target.write_text("<p>b</p>", encoding="utf-8")
    page = markdown_to_page("# N\n\n![p](p.png)\n", "notes")
    extras.page_extras("html", "notes.md", original, page, "<p>b</p>", target, False, True, "LandingPage")
    assert '<base href="file:///' in seen["text"] and "p.png" in seen["text"]
    assert not (tmp_path / "before.html").exists()


def test_a_failed_screenshot_is_a_note_and_not_a_crash(tmp_path, monkeypatch):
    def broken(shots):
        raise screenshot.ScreenshotError("expected a browser to launch, run playwright install chromium (no luck)")

    monkeypatch.setattr(extras, "capture", broken)
    original = tmp_path / "page.html"
