import html
import json
import re

from bs4 import BeautifulSoup, Comment, NavigableString, Tag

# What a React component cannot carry over from the page.
SKIPPED = {"script", "style", "link", "meta", "title", "base", "noscript", "head"}
VOID = {"area", "base", "br", "col", "embed", "hr", "img", "input", "link", "meta", "source", "track", "wbr"}
INLINE = {"a", "span", "b", "strong", "em", "i", "code", "small", "u", "img", "button", "input",
          "label", "select", "mark", "sub", "sup", "abbr", "time", "kbd"}
BOOLEAN = {"disabled", "required", "hidden", "multiple", "open", "readonly", "autofocus", "novalidate",
           "reversed", "controls", "loop", "muted", "autoplay", "playsinline", "allowfullscreen"}
RENAMED = {
    "class": "className", "for": "htmlFor", "tabindex": "tabIndex", "colspan": "colSpan",
    "rowspan": "rowSpan", "maxlength": "maxLength", "minlength": "minLength", "readonly": "readOnly",
    "autocomplete": "autoComplete", "autofocus": "autoFocus", "crossorigin": "crossOrigin",
    "enctype": "encType", "novalidate": "noValidate", "srcset": "srcSet", "usemap": "useMap",
    "contenteditable": "contentEditable", "datetime": "dateTime", "frameborder": "frameBorder",
    "allowfullscreen": "allowFullScreen", "playsinline": "playsInline", "accept-charset": "acceptCharset",
}
PLAIN_VALUE = re.compile(r'^[^"{}\\\n&<>]*$')
TEXT_INPUTS_WITH_STATE = {"checkbox", "radio", "submit", "button", "reset", "hidden", "image"}

TOGGLE = (
    '<button type="button" aria-label="Toggle dark mode" onClick={() => setDark(!dark)} '
    'className="fixed right-4 top-4 z-50 rounded-full bg-white/80 p-3 shadow-lg backdrop-blur '
    'transition hover:scale-110 dark:bg-slate-800/80">'
    '{dark ? <Sun className="h-5 w-5" /> : <Moon className="h-5 w-5" />}</button>'
)
ARROW = '<ArrowRight className="ml-2 inline h-4 w-4" />'


def landing_page_tsx(page: str, component: str = "LandingPage") -> str:
    """Write a React component for a swept page. The result is generated only and never read back."""
    soup = BeautifulSoup(page.removeprefix("\ufeff"), "html.parser")
    body = soup.find("body") or soup
    icons: set[str] = set()
    toggle = body.find("button", id="theme-toggle") is not None
    if toggle:
        icons.update({"Moon", "Sun"})

    lines: list[str] = []
    for child in body.children:
        lines.extend(_render(child, 3, False, icons))
    wrapper = " ".join(body.get("class") or []) if isinstance(body, Tag) else ""

    out = [
        '// Generated by de-slopper. Needs react, lucide-react and Tailwind with darkMode: "class".',
        "// Add the Inter font to the app shell. The page's own scripts are not carried over.",
    ]
    if toggle:
        out.append('import { useEffect, useState } from "react";')
    if icons:
        out.append(f'import {{ {", ".join(sorted(icons))} }} from "lucide-react";')
    out += ["", f"export default function {component}() {{"]
    if toggle:
        out += [
            "  const [dark, setDark] = useState(false);",
            "",
            "  useEffect(() => {",
            '    document.documentElement.classList.toggle("dark", dark);',
            "  }, [dark]);",
            "",
        ]
    out += ["  return (", f"    <div className={_quote(wrapper)}>", *lines, "    </div>", "  );", "}", ""]
    return "\n".join(out)


def _render(node, depth: int, preserve: bool, icons: set[str]) -> list[str]:
    pad = "  " * depth
    if isinstance(node, Comment) or not isinstance(node, (Tag, NavigableString)):
        return []
    if isinstance(node, NavigableString):
        return _text(node, pad, preserve)
    if node.name in SKIPPED:
        return []
    if node.name == "button" and node.get("id") == "theme-toggle":
        return [pad + TOGGLE]

    name = node.name
    attributes = _attributes(node)
    if name in VOID:
        return [f"{pad}<{name}{attributes} />"]
    if name == "textarea":
        value = f" defaultValue={{{json.dumps(node.get_text(), ensure_ascii=False)}}}"
        return [f"{pad}<{name}{attributes}{value} />"]

    inner: list[str] = []
    keep = preserve or name == "pre"
    children = list(node.children)
    for position, child in enumerate(children):
        if isinstance(child, NavigableString) and not isinstance(child, Comment) and not keep:
            inner.extend(_spaced(child, children, position, pad + "  "))
        else:
            inner.extend(_render(child, depth + 1, keep, icons))
    if name == "a" and node.has_attr("data-cta"):
        icons.add("ArrowRight")
        inner.append(pad + "  " + ARROW)
    if not inner:
        return [f"{pad}<{name}{attributes}></{name}>"]
    return [f"{pad}<{name}{attributes}>", *inner, f"{pad}</{name}>"]


def _spaced(text: NavigableString, siblings: list, position: int, pad: str) -> list[str]:
    """A text node, with a literal space kept where it separates it from an inline neighbour."""
    value = str(text)
    words = " ".join(value.split())
    before = siblings[position - 1] if position else None
    after = siblings[position + 1] if position + 1 < len(siblings) else None

    def inline(sibling) -> bool:
        return isinstance(sibling, Tag) and sibling.name in INLINE

    lines = []
    if value[:1].isspace() and inline(before) and words:
        lines.append(pad + '{" "}')
    if words:
        lines.append(pad + _escape(words))
    elif value and inline(before) and inline(after):
        lines.append(pad + '{" "}')
    if words and value[-1:].isspace() and inline(after):
        lines.append(pad + '{" "}')
    return lines


def _text(node: NavigableString, pad: str, preserve: bool) -> list[str]:
    value = str(node)
    if preserve:
        return [pad + "{" + json.dumps(value, ensure_ascii=False) + "}"] if value else []
    words = " ".join(value.split())
    return [pad + _escape(words)] if words else []


def _escape(text: str) -> str:
    escaped = html.escape(text, quote=False)
    return re.sub(r"[{}]", lambda found: '{"' + found.group() + '"}', escaped)


def _quote(value: str) -> str:
    return f'"{value}"' if PLAIN_VALUE.match(value) else "{" + json.dumps(value, ensure_ascii=False) + "}"


def _attributes(tag: Tag) -> str:
    parts = []
    kind = str(tag.get("type") or "text").lower()
    for raw, value in tag.attrs.items():
        name = raw.lower()
        if isinstance(value, list):
            value = " ".join(value)
        value = str(value)
        if name == "style" or name.startswith("on") or (name == "id" and value == "theme-toggle"):
            continue
        if tag.name == "option" and name == "selected":
            continue
        if name == "checked":
            parts.append("defaultChecked")
            continue
        if name == "value" and tag.name == "input" and kind not in TEXT_INPUTS_WITH_STATE:
            name = "defaultValue"
        if name in BOOLEAN:
            parts.append(RENAMED.get(name, name))
            continue
        parts.append(f"{_jsx_name(name)}={_quote(value)}")
    return "".join(" " + part for part in parts)


def _jsx_name(name: str) -> str:
    if name in RENAMED:
        return RENAMED[name]
    if name.startswith(("data-", "aria-")):
        return name
    if ":" in name:
        head, _, rest = name.partition(":")
        return head + rest[:1].upper() + rest[1:]
    head, *rest = name.split("-")
    return head + "".join(piece[:1].upper() + piece[1:] for piece in rest)
