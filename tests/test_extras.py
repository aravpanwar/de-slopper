PAGE = (
    '<html><head><title>T</title><script>var gone = 1;</script></head>'
    '<body class="font-sans bg-white">\n'
    '<button id="theme-toggle">x</button>\n'
    '<h1 class="text-4xl" style="color: red">Hello {world} <b>now</b></h1>\n'
    '<p>Call <a href="a.html?x=1&y=2" data-cta="">us</a> if 1 < 2.</p>\n'
    '<label for="q">Name</label><input id="q" name="q" value="Gustav" maxlength="9" readonly>\n'
    '<input type="checkbox" name="c" checked><input type="submit" value="Go">\n'
    '<textarea name="t">line one\nline two</textarea>\n'
    '<select name="s"><option selected value="a">A</option></select>\n'
    '<pre><code>  indented\n    more</code></pre>\n'
    '<svg viewBox="0 0 2 2"><path stroke-width="2" xlink:href="#a"></path></svg>\n'
    '<img src="p.png" alt="" onclick="evil()">\n'
    "</body></html>\n"
)


def test_the_page_becomes_a_component_with_a_lucide_import():
    tsx = landing_page_tsx(PAGE)
    assert tsx.startswith("// Generated by de-slopper.")
    assert 'import { useEffect, useState } from "react";' in tsx
    assert 'import { ArrowRight, Moon, Sun } from "lucide-react";' in tsx
    assert "export default function LandingPage() {" in tsx
    assert "const [dark, setDark] = useState(false);" in tsx
    assert '<div className="font-sans bg-white">' in tsx
    assert "onClick={() => setDark(!dark)}" in tsx and "<Moon" in tsx and "<Sun" in tsx


def test_markup_is_translated_to_jsx_and_nothing_executable_is_carried_over():
    tsx = landing_page_tsx(PAGE)
    assert "class=" not in tsx and "<script" not in tsx and "var gone" not in tsx
    assert "style=" not in tsx and "onclick" not in tsx.lower().replace("onclick={", "")
    assert 'className="text-4xl"' in tsx
    assert 'htmlFor="q"' in tsx and 'maxLength="9"' in tsx and " readOnly" in tsx
    assert 'defaultValue="Gustav"' in tsx and "defaultChecked" in tsx
    assert 'defaultValue={"line one\\nline two"}' in tsx
    assert 'strokeWidth="2"' in tsx and 'xlinkHref="#a"' in tsx
    assert '<img src="p.png" alt="" />' in tsx
    assert 'href={"a.html?x=1&y=2"}' in tsx
    assert 'Hello {"{"}world{"}"}' in tsx and "1 &lt; 2." in tsx
    assert '{"  indented\\n    more"}' in tsx
    assert 'value="Go"' in tsx and "<option value=\"a\">" in tsx
    assert '{" "}' in tsx
    assert "<ArrowRight" in tsx


def test_a_page_without_a_toggle_or_a_call_to_action_needs_no_imports():
    tsx = landing_page_tsx("<body><p>hi</p></body>", "Plain")
    assert "export default function Plain()" in tsx
    assert "import " not in tsx and "useState" not in tsx


def test_markdown_becomes_a_plain_page_with_a_title():
    page = markdown_to_page("# Gustav's *clocks*\n\nSome [link](a.html) and ![pic](p.png).\n\n- one\n- two\n\n"
                            "| a | b |\n|---|---|\n| 1 | 2 |\n", "fallback")
    assert "<title>Gustav's clocks</title>" in page
    assert "<h1>Gustav's <em>clocks</em></h1>" in page
    assert '<a href="a.html">link</a>' in page and '<img alt="pic" src="p.png" />' in page
    assert "<li>one</li>" in page and "<table>" in page
    assert "<title>fallback</title>" in markdown_to_page("no heading", "fallback")


def test_a_markdown_file_is_swept_as_a_page(tmp_path, monkeypatch):
    monkeypatch.setenv("DESLOPPER_CACHE_DIR", str(tmp_path / "cache"))
    notes = tmp_path / "notes.md"
    notes.write_text("# Notes\n\nSee ![pic](p.png) and [home](index.html).\n", encoding="utf-8")
    (tmp_path / "p.png").write_bytes(b"png")
    before = notes.read_bytes()
    out = tmp_path / "out" / "notes.html"
    args = cli.build_parser().parse_args([str(notes), "-o", str(out), "--provider", "dummy"])
    assert cli.run(args) == 0
    page = out.read_text(encoding="utf-8")
    assert "<h1>Notes</h1>" in page and 'href="index.html"' in page
    assert (out.parent / "p.png").read_bytes() == b"png"
    assert notes.read_bytes() == before


def test_a_directory_run_sweeps_markdown_into_html_and_keeps_the_input(tmp_path, monkeypatch):
    monkeypatch.setenv("DESLOPPER_CACHE_DIR", str(tmp_path / "cache"))
    src = tmp_path / "docs"
    (src / "guide").mkdir(parents=True)
    (src / "README.md").write_text("# Hi\n\ntext\n", encoding="utf-8")
    (src / "guide" / "start.md").write_text("# Start\n", encoding="utf-8")
    before = {p: p.read_bytes() for p in src.rglob("*.md")}
    out = tmp_path / "out"
    args = cli.build_parser().parse_args([str(src), "-o", str(out), "--provider", "dummy"])
    assert cli.run(args) == 0
    assert "<h1>Hi</h1>" in (out / "README.html").read_text(encoding="utf-8")
    assert (out / "guide" / "start.html").exists() and not (out / "README.md").exists()
    assert {p: p.read_bytes() for p in src.rglob("*.md")} == before


def test_react_writes_a_component_next_to_the_page(tmp_path, monkeypatch):
    monkeypatch.setenv("DESLOPPER_CACHE_DIR", str(tmp_path / "cache"))
    page = tmp_path / "page.html"
    page.write_text(PAGE, encoding="utf-8")
    out = tmp_path / "out" / "page.html"
    receipt = tmp_path / "r.jsonl"
    args = cli.build_parser().parse_args(
        [str(page), "-o", str(out), "--provider", "dummy", "--react", "--receipt", str(receipt)])
    assert cli.run(args) == 0
    tsx = (out.parent / "LandingPage.tsx").read_text(encoding="utf-8")
    assert "from \"lucide-react\"" in tsx
    rows = [json.loads(row) for row in receipt.read_text(encoding="utf-8").splitlines()]
    assert {"file": "page.html", "kind": "react", "status": "applied", "detail": "wrote LandingPage.tsx"} in rows


def test_react_in_a_directory_run_names_each_component_after_its_page(tmp_path, monkeypatch):
    monkeypatch.setenv("DESLOPPER_CACHE_DIR", str(tmp_path / "cache"))
    src = tmp_path / "site"
    src.mkdir()
    (src / "home-page.html").write_text("<body><p>a</p></body>", encoding="utf-8")
