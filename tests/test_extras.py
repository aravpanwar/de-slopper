class FakePage:
    def __init__(self, log):
        self.log = log

    def goto(self, url, **options):
        self.log.append(("goto", url, options["wait_until"]))

    def wait_for_timeout(self, ms):
        pass

    def screenshot(self, path, full_page):
        self.log.append(("shot", path, full_page))


class FakeBrowser:
    def __init__(self, log):
        self.log = log

    def new_context(self, **options):
        self.log.append(("context", options["color_scheme"], options["reduced_motion"]))
        return types.SimpleNamespace(new_page=lambda: FakePage(self.log))

    def close(self):
        self.log.append(("closed",))


def fake_playwright(monkeypatch, log, failures):
    def launch(**options):
        log.append(("launch", options))
        if failures and len(log) <= failures:
            raise RuntimeError("Executable doesn't exist\nmore")
        return FakeBrowser(log)

    class Manager:
        def __enter__(self):
            return types.SimpleNamespace(chromium=types.SimpleNamespace(launch=launch))

        def __exit__(self, *exc):
            return False

    module = types.ModuleType("playwright.sync_api")
    module.sync_playwright = Manager
    monkeypatch.setitem(sys.modules, "playwright.sync_api", module)


def test_the_browser_falls_back_to_edge_and_the_page_is_captured_whole(monkeypatch, tmp_path):
    log = []
    fake_playwright(monkeypatch, log, failures=1)
    screenshot.capture([("file:///a.html", tmp_path / "deep" / "a.png")])
    assert [entry[0] for entry in log] == ["launch", "launch", "context", "goto", "shot", "closed"]
    assert log[1] == ("launch", {"channel": "msedge"})
    assert log[2] == ("context", "light", "reduce")
    assert log[3] == ("goto", "file:///a.html", "networkidle") and log[4][2] is True
    assert (tmp_path / "deep").is_dir()


